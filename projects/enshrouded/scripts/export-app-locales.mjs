import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export async function exportAppLocales(root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")) {
  const locales = path.join(root, "src/i18n/locales");
  const languages = JSON.parse(await readFile(path.join(root, "scripts/enshrouded-languages.json"), "utf8"));
  const englishBytes = await readFile(path.join(locales, "en.json"));
  const sourceSha256 = createHash("sha256").update(englishBytes).digest("hex");
  const output = path.join(root, "public/data/enshrouded/app-locales");
  await mkdir(output, { recursive: true });
  const manifest = { version: 1, sourceSha256, languages: {} };
  for (const language of Object.keys(languages)) {
    const translation = JSON.parse(await readFile(path.join(locales, `${language.toLowerCase()}.json`), "utf8"));
    const bytes = JSON.stringify({ version: 1, language, sourceSha256, translation }) + "\n";
    const file = `${language.toLowerCase()}.json`;
    await writeFile(path.join(output, file), bytes);
    manifest.languages[language] = { file, size: Buffer.byteLength(bytes), sha256: createHash("sha256").update(bytes).digest("hex") };
  }
  await writeFile(path.join(output, "manifest.json"), JSON.stringify(manifest) + "\n");
  const generated = `// Generated by scripts/export-app-locales.mjs.\nexport const APP_LOCALE_SOURCE_SHA256 = ${JSON.stringify(sourceSha256)};\n`;
  const versionPath = path.join(root, "src/i18n/app-locale-version.ts");
  let previous;
  try { previous = await readFile(versionPath, "utf8"); } catch (error) { if (error.code !== "ENOENT") throw error; }
  if (previous !== generated) await writeFile(versionPath, generated);
  console.log(`Exported ${Object.keys(languages).length} app UI locales for CDN delivery.`);
  return manifest;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) await exportAppLocales();
