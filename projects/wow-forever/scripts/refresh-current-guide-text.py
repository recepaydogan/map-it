"""Remove advice about retired talents and correct exact stale tuning statements.

English authored guidance only. Translation overlays and historical change logs
are deliberately excluded. Current rank explanations live in the talent records.
"""
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
current = json.loads((ROOT / "public/data/classes/talent-calculator.json").read_text(encoding="utf8"))["classes"]
old = json.loads(subprocess.check_output(["git", "show", "HEAD:public/data/classes/talent-calculator.json"], cwd=ROOT))["classes"]
removed = {}
for cls in current:
    before = next(c for c in old if c["n"] == cls["n"])
    names = {t["n"] for tree in cls["trees"] for t in tree["talents"]}
    removed[cls["n"].lower()] = {t["n"] for tree in before["trees"] for t in tree["talents"]} - names
removed["druid"].add("Berserk")
removed["mage"].add("Frost Blast")
class_ids = {"warrior":1,"paladin":2,"hunter":3,"rogue":4,"priest":5,"shaman":7,"mage":8,"warlock":9,"druid":11}
spell_facts = {}
for i in range(64):
    for spell in json.loads((ROOT / f"public/data/spells/foreverdb/{i}.json").read_text(encoding="utf8")).values():
        if spell.get("cl") and spell.get("d") and not spell.get("retired"):
            key = (spell["cl"],spell["n"])
            if key not in spell_facts: spell_facts[key] = spell["d"].split("\n")[0]
talent_facts = {(cls["n"].lower(),t["n"]):t["d"][0] for cls in current for tree in cls["trees"] for t in tree["talents"]}

def stale(value, class_id):
    return any(re.search(r"(?<!\w)" + re.escape(name) + r"(?!\w)", value) for name in removed.get(class_id, set())) or (
        class_id == "rogue" and "Venom" in value and bool(re.search(r"finishing move|finisher|Combo Point|cast Venom|refresh Venom", value, re.I)))

def prose(value, class_id):
    value = value.replace("Improved Fireball", "Accelerant").replace("Elemental Precision", "Precision") if class_id == "mage" else value
    if "<" in value:
        # Drop complete obsolete prose/list blocks; keep balanced markup intact.
        value = re.sub(r"<(p|li)\b[^>]*>(?:(?!</?\1\b)[\s\S])*?</\1>", lambda m: "" if stale(m[0], class_id) else m[0], value)
    else:
        sentences = re.split(r"(?<=[.!?])\s+(?=[A-Z])", value)
        value = " ".join(sentence for sentence in sentences if not stale(sentence, class_id))
    if "Arcane Blast" in value:
        value = value.replace("mana cost by 175%", "mana cost by 100%").replace("mana cost is increased by 175%", "mana cost is increased by 100%")
        value = value.replace("gain 15% of your Intellect", "gain 12% of your Intellect").replace("lasts 15 sec from time of initial application", "lasts 18 sec from time of initial application")
    if "Shifting Power" in value: value = value.replace("16 sec cooldown", "8 sec cooldown")
    if "Ice Lance" in value:
        value = value.replace("throw Ice Lances", "cast Ice Lance when its 8 sec cooldown is ready").replace("throw the Lances right away", "cast Ice Lance when its 8 sec cooldown is ready")
    if "Flurry" in value and class_id in ["warrior", "shaman"]: value = value.replace("25%", "30%")
    if "Mutilate" in value and class_id == "rogue": value = value.replace("75% weapon", "90% weapon")
    if "Riptide" in value and class_id == "shaman": value = value.replace("6 sec cooldown", "12 sec cooldown")
    if class_id == "warrior":
        value = value.replace("threat generated by 30%", "threat generated by 80%")
        value = value.replace("raises all your threat by 30%", "raises all your threat by 80%").replace("30% more threat", "80% more threat")
        value = value.replace("Defensive Stance's tooltip now states the threat bonus, 30%", "Defensive Stance's tooltip now states the threat bonus, 80%")
        if "Slam" in value: value = value.replace("(18 sec base)", "(15 sec base)")
    if class_id == "paladin":
        value = re.sub(r"(Increases your Physical and Holy damage dealt by \d+% for 30 sec after landing a non-periodic critical strike\. Stacks up to )3( times\.)", r"\g<1>5\2", value)
    if class_id == "druid":
        value = value.replace("Ferocious Bite, a finisher for targets that are about to die, arrives at 32, above the current level 30 cap.", "Ferocious Bite, a finisher for targets that are about to die, is learned at level 24.")
        value = value.replace("Ferocious Bite comes at 32, Dire Bear Form at 40 and Lacerate at 42, all above the current level 30 cap.", "Ferocious Bite is learned at 24. Dire Bear Form comes at 40 and Lacerate at 42, both above the current level 30 cap.")
    if class_id == "shaman": value = value.replace(">Totemic Recall</a>", ">Totemic Call</a>")
    return value

def walk(value, class_id):
    if isinstance(value, str): return prose(value, class_id)
    if isinstance(value, list):
        return [walk(row, class_id) for row in value if not (isinstance(row, str) and stale(row, class_id) and len(row) < 55)
                and not (isinstance(row, dict) and any(stale(row.get(k, ""), class_id) for k in ["ability", "spell"]))]
    if isinstance(value, dict):
        result = {k: walk(v, class_id) for k, v in value.items()}
        if result.get("note") == "":
            name = result.get("ability",result.get("spell"))
            fact = talent_facts.get((class_id,name)) or spell_facts.get((class_ids.get(class_id),name))
            if fact: result["note"] = fact
        if result.get("summary") == "" and isinstance(result.get("why"),dict):
            result["summary"] = " ".join(list(dict.fromkeys(result["why"].values()))[:3])
        return result
    return value

paths = [(ROOT / f"public/data/classes/guides/{cls['n'].lower()}-{kind}.json", cls["n"].lower()) for cls in current for kind in ["play", "builds"]]
paths += [(ROOT / f"public/data/guides/leveling-{cls['n'].lower()}.json", cls["n"].lower()) for cls in current]
changed = []
for path, class_id in paths:
    before = json.loads(path.read_text(encoding="utf8"))
    after = walk(before, class_id)
    if before != after:
        temporary = path.with_suffix(".november-update.tmp")
        temporary.write_text(json.dumps(after, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf8")
        temporary.replace(path)
        changed.append(str(path.relative_to(ROOT)))
path = ROOT / "public/data/classes/guides/class-guides.json"
guides = json.loads(path.read_text(encoding="utf8"))
for class_name, guide in guides["classes"].items(): guides["classes"][class_name] = walk(guide, class_name.lower())
temporary = path.with_suffix(".november-update.tmp")
temporary.write_text(json.dumps(guides, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf8")
temporary.replace(path)
print("Corrected obsolete advice in", len(changed), "English guide files and shared summaries")
