import test from "node:test";
import assert from "node:assert/strict";
import { access, readFile } from "node:fs/promises";

const json = async (path) => JSON.parse(await readFile(path, "utf8"));
const catalog = await json("public/data/classes/talent-calculator.json");
const metadata = await json("public/data/spells/foreverdb/classes.json");
const shards = await Promise.all(Array.from({ length: 64 }, (_, i) => json(`public/data/spells/foreverdb/${i}.json`)));
const spell = (id) => shards[id % 64][id];
const tree = (cls, name) => catalog.classes.find((c) => c.n === cls).trees.find((t) => t.n === name);
const talent = (cls, tr, name) => tree(cls, tr).talents.find((t) => t.n === name);

test("launch calculator has unique cells, valid prerequisites and matching class browser metadata", () => {
  const ids = new Set();
  for (const cls of catalog.classes) for (const tr of cls.trees) {
    const cells = new Set();
    const view = metadata.find((c) => c.n === cls.n).trees.find((t) => t.n === tr.n);
    assert.equal(view.talents.length, tr.talents.length);
    for (const t of tr.talents) {
      assert.ok(!ids.has(t.id), `duplicate ID ${t.id}`); ids.add(t.id);
      const cell = `${t.row}:${t.col}`;
      assert.ok(!cells.has(cell), `${cls.n}/${tr.n}/${cell}`); cells.add(cell);
      assert.equal(t.d.length, t.ranks.length, t.n);
      for (const [id, rank] of t.pre) {
        const parent = tr.talents.find((p) => p.id === id);
        assert.ok(parent && parent.row <= t.row && rank < parent.ranks.length, t.n);
      }
      const linked = view.talents.find((p) => p.id === t.id);
      for (const key of ["n", "d", "ranks", "row", "col", "pre"]) assert.deepEqual(linked[key], t[key], `${t.n}/${key}`);
    }
  }
  assert.equal(talent("Warrior", "Fury", "Flurry").ranks.length, 3);
  assert.equal(talent("Warrior", "Arms", "Bloodthrill").ranks.length, 2);
  assert.equal(talent("Warrior", "Arms", "Improved Tactical Mastery").ranks.length, 3);
  assert.equal(talent("Rogue", "Assassination", "Seal Fate").ranks.length, 3);
  assert.equal(talent("Rogue", "Assassination", "Mutilate").row, 6);
  assert.equal(talent("Rogue", "Assassination", "Venom").row, 4);
  assert.equal(talent("Rogue", "Combat", "Flash of Steel").ranks.length, 5);
  assert.equal(talent("Rogue", "Subtlety", "Boot Knife").ranks.length, 5);
});

test("new Rogue abilities use actual class IDs, ranks, costs, icons and talent ownership", async () => {
  const rogue = metadata.find((c) => c.id === 4);
  const shank = rogue.abilities.find((a) => a.n === "Shank");
  assert.deepEqual(shank.ranks.map((r) => [r.id, r.lv]), [[1329283, 24], [1329549, 44]]);
  for (const [id, energy] of [[1329283, 15], [1329549, 25]]) {
    const s = spell(id);
    assert.equal(s.cl, 4); assert.equal(s.cd, 10000);
    assert.deepEqual(s.co, [[5, "Energy", 0]]);
    assert.ok(s.ef.some((e) => e.e === 30 && e.v === energy));
    assert.ok(!s.d.includes("["), s.d);
    await access(`public/data/spells/icons/${s.ic}.webp`);
  }
  assert.equal(spell(1328825).lv, 18);
  assert.equal(spell(1328829).lv, 32);
  assert.equal(spell(1329555).cd, 15000);
  assert.deepEqual(spell(1329555).co, [[25, "Health", 1]]);
  assert.deepEqual(rogue.abilities.find((a) => a.n === "Death Mark").ranks.map((r) => r.id), [1316709, 1325756, 1325757, 1325758]);
  assert.equal(talent("Rogue", "Subtlety", "Death Mark").ranks[0], 1316709);
});

test("announced threat values and all Riptide ranks agree with spell details", () => {
  assert.match(spell(71).d, /threat generated by 80%/);
  assert.ok(spell(21178).ef.some((e) => e.a === 10 && e.v === 115));
  assert.deepEqual(talent("Warrior", "Protection", "Defiance").d.map((d) => Number(d.match(/(\d+)%/)[1])), [7, 13, 20]);
  const shaman = metadata.find((c) => c.id === 7);
  for (const rank of shaman.abilities.find((a) => a.n === "Riptide").ranks) {
    const s = spell(rank.id);
    assert.equal(s.cd, 12000);
    assert.ok(!s.ef.some((e) => e.e === 10), `${rank.id}: stale initial heal`);
    assert.ok(!/an additional/.test(s.d), s.d);
  }
  assert.ok(talent("Shaman", "Elemental", "Call of Thunder"));
  assert.ok(talent("Shaman", "Elemental", "Lightning Mastery"));
  assert.equal(talent("Shaman", "Enhancement", "Stormstrike").d[0].includes("150%"), true);
  assert.equal(spell(17364).cd, 6000);
});

test("removed playable abilities stay historical and current talents contain no retired references", () => {
  for (const cls of metadata) {
    assert.ok(!cls.abilities.some((a) => ["Frost Blast", "Lava Burst", "Binding Heal"].includes(a.n)));
    for (const tr of cls.trees) for (const t of tr.talents) {
      assert.ok(!t.d.some((d) => /Frost Blast|Lava Burst/.test(d)), t.n);
    }
  }
  for (const id of [1326053, 1326054, 1326055, 408490, 1310703]) {
    assert.equal(spell(id).retired, true);
    assert.equal(spell(id).cl, 0);
  }
});
