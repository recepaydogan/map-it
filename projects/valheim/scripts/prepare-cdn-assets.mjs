import fs from 'node:fs/promises'
import path from 'node:path'
import { validateMapTextures } from './map-texture-files.mjs'
import { root, manifestPath, collectAssets, contentHash } from './asset-cdn-files.mjs'

const manifest = JSON.parse(await fs.readFile(manifestPath, 'utf8'))
const files = await collectAssets()
validateMapTextures(path.join(root, 'public'))
if (contentHash(manifest.files) !== manifest.contentHash) throw new Error('Invalid CDN release manifest')
const published = new Map(manifest.files.map(file => [file.path, file.sha256]))
if (files.some(file => published.get(file.path) !== file.sha256)) throw new Error('PNG assets changed. Run npm run upload:assets before building.')
if (!manifest.verifiedAt || !manifest.baseUrl.startsWith('https://')) throw new Error('A verified HTTPS CDN release is required')
// Keep catalog URLs reproducible after a fresh extraction or a new CDN release.
const pattern = /(?:https:\/\/[^"\s]+?\/valheim\/assets\/[a-f0-9]+)?\/game-data\/(icons)\//g
async function rewrite(directory) {
  for (const entry of await fs.readdir(directory, { withFileTypes: true })) {
    const file = path.join(directory, entry.name)
    if (entry.isDirectory()) await rewrite(file)
    else if (entry.name.endsWith('.json') && file !== manifestPath) {
      const old = await fs.readFile(file, 'utf8')
      const next = old.replace(pattern, `${manifest.baseUrl}/game-data/$1/`)
        .replace(/https:\/\/[^"\s]+?\/valheim\/assets\/[a-f0-9]+\/game-data\/map-textures\//g, '/game-data/map-textures/')
      if (next !== old) { await fs.writeFile(`${file}.tmp`, next); await fs.rename(`${file}.tmp`, file) }
    }
  }
}
await rewrite(path.join(root, 'public/game-data'))
await fs.writeFile(path.join(root, 'src/lib/asset-cdn-config.ts'), `// Generated by prepare-cdn-assets.mjs; public URL only.\nexport const ASSET_CDN_BASE_URL = ${JSON.stringify(manifest.baseUrl)}\n`)
console.log(`CDN release ready: ${manifest.files.length} PNGs, ${manifest.contentHash}`)
