create table public.expeditions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  scene text not null,
  started_at bigint not null,
  updated_at bigint not null,
  record jsonb not null,
  created_at timestamptz not null default now(),
  unique (user_id, scene, started_at)
);

create index expeditions_user_updated_at_idx
  on public.expeditions (user_id, updated_at desc);

alter table public.expeditions enable row level security;

create policy "Users can read their own expeditions"
  on public.expeditions
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

create policy "Users can insert their own expeditions"
  on public.expeditions
  for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

create policy "Users can update their own expeditions"
  on public.expeditions
  for update
  to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

create policy "Users can delete their own expeditions"
  on public.expeditions
  for delete
  to authenticated
  using ((select auth.uid()) = user_id);
