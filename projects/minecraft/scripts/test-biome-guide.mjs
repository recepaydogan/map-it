import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { parseBiomeGuideArtifact } from "../src/features/knowledge/biome-guide-artifact.ts";
import { createBiomeGuideIndex } from "../src/features/knowledge/biome-guide-data.ts";
import { GAME_GUIDE_BIOME_LANDMARKS, GAME_GUIDE_BIOME_RESOURCES } from "../src/game-config.ts";

const json = async path => JSON.parse(await readFile(new URL(path, import.meta.url), "utf8"));
const artifact = await json("../public/knowledge-data/bedrock/26.45/biomes.json");
const bedrock = parseBiomeGuideArtifact(artifact, { edition: "bedrock", version: "26.45" });
assert.equal(bedrock.biomes.size, 61);
assert.equal(bedrock.biomes.get("minecraft:plains")?.temperature, 0.8);
assert.equal(bedrock.biomes.get("minecraft:nether_wastes")?.sourceId, "minecraft:hell");
assert.ok(!bedrock.biomes.has("minecraft:dappled_forest"));
assert.throws(() => parseBiomeGuideArtifact(artifact, { edition: "java", version: "26.3" }));
const bedrockIndex = createBiomeGuideIndex({ items: null, recipes: null, mechanics: null, biomes: bedrock }, "bedrock");
assert.equal(bedrockIndex.size, 61);
assert.equal(bedrockIndex.get("minecraft:nether_wastes")?.dimension, "nether");
assert.ok(bedrockIndex.get("minecraft:plains")?.spawns.some(ref => ref.id === "minecraft:sheep"));
assert.ok(bedrockIndex.get("minecraft:plains")?.spawns.some(ref => ref.id === "minecraft:bee"));
assert.ok(bedrockIndex.get("minecraft:plains")?.spawns.some(ref => ref.id === "minecraft:horse"));
assert.ok(!bedrockIndex.get("minecraft:nether_wastes")?.spawns.some(ref => ref.id === "minecraft:cod"));
assert.ok(!bedrockIndex.get("minecraft:nether_wastes")?.spawns.some(ref => ref.id === "minecraft:polar_bear"));
assert.ok(bedrockIndex.get("minecraft:the_end")?.spawns.some(ref => ref.id === "minecraft:enderman"));
const wildernessArtifact = await json("../public/knowledge-data/bedrock/26.52/biomes.json");
const wilderness = parseBiomeGuideArtifact(wildernessArtifact, { edition: "bedrock", version: "26.52" });
assert.equal(wilderness.biomes.size, 62);
assert(wilderness.biomes.has("minecraft:dappled_forest"));
assert(GAME_GUIDE_BIOME_LANDMARKS.dappled_forest.includes("minecraft:abandoned_camp"));
assert(GAME_GUIDE_BIOME_RESOURCES.dappled_forest.includes("minecraft:shelf_mushroom"));
const wildernessIndex = createBiomeGuideIndex({ items: null, recipes: null, mechanics: null, biomes: wilderness }, "bedrock");
assert(wildernessIndex.get("minecraft:dappled_forest")?.spawns.some(ref => ref.id === "minecraft:fox"));

const javaMechanics = await json("../public/knowledge-data/java/26.3/mechanics.json");
const java = createBiomeGuideIndex({ items: null, recipes: null, mechanics: javaMechanics }, "java");
assert.ok(java.size >= 60);
assert.equal(java.get("minecraft:plains")?.temperature, 0.8);
assert.ok(java.get("minecraft:plains")?.spawns.some(ref => ref.id === "minecraft:sheep"));
assert.equal(java.get("minecraft:badlands")?.precipitation, false);
const oldMechanics = await json("../public/knowledge-data/java/1.21.11/mechanics.json");
assert.equal(createBiomeGuideIndex({ items: null, recipes: null, mechanics: oldMechanics }, "java").size, 0);
console.log(`Biome guide tests passed: ${java.size} Java and ${bedrockIndex.size} Bedrock records.`);
